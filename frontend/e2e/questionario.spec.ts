import {test, expect} from '@playwright/test';
import {readFileSync} from 'node:fs';

test('questionário salva respostas, compõe instruções e permite voltar ao texto livre', async ({page}) => {
    await page.goto('/');
    await page.getByLabel('E-mail', {exact:true}).fill('browser@example.test');
    await page.getByLabel('Senha', {exact:true}).fill(readFileSync(process.env['E2E_CREDENTIAL_FILE']!, 'utf8'));
    await page.getByRole('button', {name:'Entrar no painel'}).click();
    await page.getByRole('button', {name:'Bot', exact:true}).click();
    await page.getByLabel('Usar configuração guiada').check();
    await page.getByLabel('Quais formas de pagamento aceita?').fill('Pix e cartão em até 3 vezes.');
    await page.getByLabel('Como funciona a entrega ou retirada?').fill('Retirada na loja.');
    await page.getByLabel('Quais são os horários de atendimento?').fill('Segunda a sexta, das 9h às 18h.');
    await page.getByLabel('O que os clientes costumam perguntar?').fill('Pergunta: Tem estacionamento? Resposta: Sim.');
    await page.getByLabel('Quando o bot deve chamar uma pessoa?').fill('Quando o cliente pedir ou houver reclamação.');
    await page.getByLabel('Instruções adicionais').fill('Não prometa descontos.');
    await page.getByRole('radio', {name:/Direto ao ponto/}).check();
    await expect(page.locator('.previa-orientacoes')).toContainText('Pix e cartão');
    const resposta = page.waitForResponse(r=>r.url().endsWith('/bot') && r.request().method()==='PUT');
    await page.getByRole('button', {name:'Salvar configurações'}).click();
    const dados = await (await resposta).json();
    expect(dados.bot.instrucoes).toContain('Pagamento: Pix e cartão');
    expect(dados.bot.instrucoes).toContain('Não prometa descontos.');
    await page.reload();
    await page.getByRole('button', {name:'Bot', exact:true}).click();
    await expect(page.getByLabel('Quais formas de pagamento aceita?')).toHaveValue('Pix e cartão em até 3 vezes.');
    await expect(page.getByLabel('Instruções adicionais')).toHaveValue('Não prometa descontos.');
    await page.getByLabel('Usar configuração guiada').uncheck();
    await expect(page.getByLabel('Quais formas de pagamento aceita?')).toBeHidden();
    await page.getByRole('button', {name:'Salvar configurações'}).click();
    await expect(page.getByRole('status').filter({hasText:'Alterações salvas.'})).toBeVisible();
    await page.reload();
    await page.getByRole('button', {name:'Bot', exact:true}).click();
    await expect(page.getByLabel('Instruções adicionais')).toHaveValue('Não prometa descontos.');
    await page.getByLabel('Usar configuração guiada').check();
    await expect(page.getByLabel('Quais formas de pagamento aceita?')).toHaveValue('Pix e cartão em até 3 vezes.');
    expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
    await page.screenshot({path:`test-results/questionario-${test.info().project.name}.png`, fullPage:true});
});
